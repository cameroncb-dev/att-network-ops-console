import { hoursAgoIso } from "@/lib/incidents/clock"
import { slaTargetHours } from "@/lib/incidents/sla"
import type {
  AssignmentGroup,
  Impact,
  Incident,
  IncidentState,
  Priority,
  Region,
  Service,
  Source,
  WorkNote,
} from "@/lib/incidents/types"

type NoteDraft = { hoursAgo: number; author: string; text: string }

type Draft = {
  number: string
  shortDescription: string
  description: string
  priority: Priority
  state: IncidentState
  assignmentGroup: AssignmentGroup
  assignedTo: string
  service: Service
  region: Region
  configurationItem: string
  location: string
  source?: Source
  openedHoursAgo: number
  resolvedHoursAgo?: number
  notes?: NoteDraft[]
}

function impactFor(priority: Priority): { impact: Impact; urgency: Impact } {
  if (priority.startsWith("1")) return { impact: "1 - High", urgency: "1 - High" }
  if (priority.startsWith("2")) return { impact: "2 - Medium", urgency: "1 - High" }
  if (priority.startsWith("3")) return { impact: "2 - Medium", urgency: "2 - Medium" }
  return { impact: "3 - Low", urgency: "3 - Low" }
}

function materialize(draft: Draft): Incident {
  const openedAt = hoursAgoIso(draft.openedHoursAgo)
  const slaDueAt = new Date(Date.parse(openedAt) + slaTargetHours(draft.priority) * 3600000).toISOString()
  const resolvedAt = draft.resolvedHoursAgo == null ? null : hoursAgoIso(draft.resolvedHoursAgo)
  if (draft.resolvedHoursAgo != null && draft.resolvedHoursAgo >= draft.openedHoursAgo) {
    throw new Error(`${draft.number} is marked resolved before it opened`)
  }
  const workNotes: WorkNote[] = (draft.notes ?? []).map((note, index) => {
    if (note.hoursAgo > draft.openedHoursAgo + 0.001) {
      throw new Error(`${draft.number} note ${index + 1} is timestamped before open`)
    }
    return {
      id: `${draft.number}-n${index + 1}`,
      at: hoursAgoIso(note.hoursAgo),
      author: note.author,
      text: note.text,
    }
  })
  workNotes.sort((a, b) => a.at.localeCompare(b.at))
  const stamps = [openedAt, resolvedAt, ...workNotes.map((note) => note.at)].filter((value): value is string => Boolean(value))
  stamps.sort()
  const severity = impactFor(draft.priority)
  return {
    number: draft.number,
    shortDescription: draft.shortDescription,
    description: draft.description,
    priority: draft.priority,
    state: draft.state,
    assignmentGroup: draft.assignmentGroup,
    assignedTo: draft.assignedTo,
    service: draft.service,
    region: draft.region,
    configurationItem: draft.configurationItem,
    location: draft.location,
    source: draft.source ?? "Alarm correlation",
    impact: severity.impact,
    urgency: severity.urgency,
    openedAt,
    updatedAt: stamps.at(-1) ?? openedAt,
    resolvedAt,
    slaDueAt,
    workNotes,
  }
}


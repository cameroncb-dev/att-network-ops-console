export function buildSeed(): Incident[] {
  const incidents = DRAFTS.map(materialize)
  const numbers = new Set(incidents.map((incident) => incident.number))
  if (numbers.size !== incidents.length) {
    throw new Error("Duplicate incident numbers in seed")
  }
  if (incidents.length < 40 || incidents.length > 60) {
    throw new Error(`Expected 40–60 incidents, got ${incidents.length}`)
  }
  if (incidents.some((incident) => incident.service === "Voice" && incident.region === "West")) {
    throw new Error("Voice in the West should stay empty so analytics can show an empty cut")
  }
  if (incidents.some((incident) => incident.service === "Fiber" && incident.region === "West")) {
    throw new Error("Fiber in the West should stay empty so analytics can show an empty cut")
  }
  if (incidents.some((incident) => incident.service === "Enterprise VPN" && incident.region === "Southwest")) {
    throw new Error("Enterprise VPN in the Southwest should stay empty so analytics can show an empty cut")
  }
  return incidents
}
